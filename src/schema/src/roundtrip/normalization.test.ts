import { describe, it } from 'vitest';
import { expectNormalized } from './roundtrip.helpers';

/**
 * Сводная таблица нормализаций: круг "парсинга + серилизации" не обязан возвращать исходную запись,
 * но обязан возвращать канонический вид, который дальше уже неподвижен.
 * Это не потери — содержимое документа сохраняется, меняется только запись.
 */

const ATTACHMENT_URL = '/api/v1/public/content/attachment/aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee';

describe('Нормализация разметки блоков', () => {
  it.each([
    ['маркер списка «дефис»', '- один\n- два', '* один\n* два'],
    ['маркер списка «плюс»', '+ один\n+ два', '* один\n* два'],
    ['делимитер нумерации «скобка»', '1) один\n2) два', '1. один\n2. два'],
    ['повторяющиеся номера', '1. один\n1. два\n1. три', '1. один\n2. два\n3. три'],
    ['горизонтальная линия звёздочками', '***', '---'],
    ['горизонтальная линия подчёркиваниями', '___', '---'],
    ['горизонтальная линия с пробелами', '- - -', '---'],
    ['setext-заголовок первого уровня', 'Заголовок\n=========', '# Заголовок'],
    ['setext-заголовок второго уровня', 'Заголовок\n---------', '## Заголовок'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация блоков кода', () => {
  it.each([
    ['тильды как ограждение', '~~~\nкод\n~~~', '```plaintext\nкод\n```'],
    ['пустая инфо-строка', '```\nкод\n```', '```plaintext\nкод\n```'],
    ['язык вне списка', '```go\nкод\n```', '```plaintext\nкод\n```'],
    ['алиас языка', '```ts\nкод\n```', '```plaintext\nкод\n```'],
    ['метаданные после языка', '```json meta=1\nкод\n```', '```json\nкод\n```'],
    ['пустое тело блока', '```json\n```', '```json\n\n```'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация инлайн-разметки', () => {
  it.each([
    ['курсив подчёркиванием', '_курсив_', '*курсив*'],
    ['жирный подчёркиваниями', '__жирный__', '**жирный**'],
    ['зачёркнутый снаружи жирного', '~~**оба**~~', '**~~оба~~**'],
    ['ссылка внутри курсива', '[*текст*](https://example.com)', '*[текст](https://example.com)*'],
    ['зачёркнутый снаружи ссылки', '~~[текст](https://example.com)~~', '[~~текст~~](https://example.com)'],
    ['пробелы по краям кода', '` код `', '`код`'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация экранирования', () => {
  it.each([
    ['одиночная звёздочка', 'текст * звезда * текст', 'текст \\* звезда \\* текст'],
    ['вертикальная черта вне таблицы', 'колонка | колонка', 'колонка \\| колонка'],
    ['скобки без ссылки', '[просто скобки]', '\\[просто скобки\\]'],
    ['чекбокс без плагина task-list', '- [ ] задача', '* \\[ \\] задача'],
    ['подчёркивание в кириллическом слове', 'очень_длинное_имя', 'очень\\_длинное\\_имя'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация таблиц', () => {
  it.each([
    ['выравнивание по левому краю', '| a |\n| :--- |\n| 1 |', '| a |\n| --- |\n| 1 |'],
    ['выравнивание по правому краю', '| a |\n| ---: |\n| 1 |', '| a |\n| --- |\n| 1 |'],
    ['выравнивание по центру', '| a |\n| :---: |\n| 1 |', '| a |\n| --- |\n| 1 |'],
    ['самозакрывающийся <br>', '| a |\n| --- |\n| раз<br/>два |', '| a |\n| --- |\n| раз<br>два |'],
    ['<br> в верхнем регистре', '| a |\n| --- |\n| раз<BR>два |', '| a |\n| --- |\n| раз<br>два |'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация медиа', () => {
  it.each([
    ['пустой alt картинки', '![](https://example.com/cat.png)', '![file](https://example.com/cat.png)'],
    ['подпись картинки отбрасывается', '![кот](https://example.com/c.png "подпись")', '![кот](https://example.com/c.png)'],
    ['подпись вложения отбрасывается', `[о.pdf](${ATTACHMENT_URL} "подпись")`, `[о.pdf](${ATTACHMENT_URL})`],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});

describe('Нормализация переводов строк и пробелов', () => {
  it.each([
    ['CRLF', 'строка1\r\nстрока2', 'строка1\nстрока2'],
    ['одиночный CR', 'строка1\rстрока2', 'строка1\nстрока2'],
    ['жёсткий перенос двумя пробелами', 'строка1  \nстрока2', 'строка1\nстрока2'],
    ['жёсткий перенос обратным слешем', 'строка1\\\nстрока2', 'строка1\nстрока2'],
    ['хвостовые пробелы строки', 'текст   \n\nдругой', 'текст\n\nдругой'],
  ])('%s', (_name, source, expected) => {
    expectNormalized(source, expected);
  });
});
