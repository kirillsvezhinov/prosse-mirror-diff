import { describe, expect, it } from 'vitest';
import { parser } from '../parser';
import { expectNormalized, expectStable } from './roundtrip.helpers';

describe('Экранированные спецсимволы переживают круг', () => {
  it.each([
    ['звёздочка', 'звезда \\* тут'],
    ['подчёркивание', 'низ \\_ тут'],
    ['квадратные скобки', 'скобки \\[тут\\]'],
    ['бэктик', 'бэктик \\` тут'],
    ['тильда', 'тильда \\~ тут'],
    ['обратный слеш', 'слеш \\\\ тут'],
    ['вертикальная черта', 'черта \\| тут'],
  ])('%s', (_name, source) => {
    expectStable(source);
  });

  it('экранирование снимается на уровне текста узла', () => {
    expect(parser.parse('звезда \\* тут').textContent).toBe('звезда * тут');
  });
});

describe('Служебные символы в начале строки', () => {
  it.each([
    ['решётка', '\\# не заголовок'],
    ['дефис', '\\- не список'],
    ['звёздочка', '\\* не список'],
    ['плюс', '\\+ не список'],
    ['больше', '\\> не цитата'],
    ['цифра с точкой', '1\\. не список'],
  ])('%s экранируется и не превращается в блок', (_name, source) => {
    expectStable(source);
    expect(parser.parse(source).firstChild?.type.name).toBe('paragraph');
  });
});

describe('Неэкранированные символы приводятся к экранированному виду', () => {
  it('одиночная звёздочка с пробелами', () => {
    expectNormalized('текст * звезда * текст', 'текст \\* звезда \\* текст');
  });

  it('вертикальная черта вне таблицы', () => {
    // escapeExtraCharacters: /\|/ применяется ко всему документу, а не только к таблицам
    expectNormalized('колонка | колонка', 'колонка \\| колонка');
  });

  it('квадратные скобки без ссылки', () => {
    expectNormalized('[просто скобки]', '\\[просто скобки\\]');
  });

  it('чекбокс task list превращается в экранированный текст', () => {
    // Плагин task-list не подключён, поэтому это обычный пункт списка с текстом
    expectNormalized('- [ ] задача\n- [x] готово', '* \\[ \\] задача\n* \\[x\\] готово');
  });
});

describe('Подчёркивание внутри слова', () => {
  it('в латинском слове не экранируется и не становится маркой', () => {
    expectStable('snake_case_name');
  });

  it('несколько подчёркиваний в латинском идентификаторе', () => {
    expectStable('very_long_variable_name');
  });

  it('подчёркивание на границе слова экранируется', () => {
    expectStable('слово \\_ другое');
  });

  it('в кириллическом слове подчёркивание экранируется', () => {
    // Исключение для внутрисловного `_` в MarkdownSerializerState.esc проверяет
    // соседние символы через /\w/, а это только ASCII — кириллица под него не попадает.
    // Текст при этом не теряется, меняется только запись.
    expectNormalized('очень_длинное_имя', 'очень\\_длинное\\_имя');
    expect(parser.parse('очень_длинное_имя').textContent).toBe('очень_длинное_имя');
  });
});

describe('Экранирование не применяется внутри кода', () => {
  it('инлайн-код с символами разметки', () => {
    expectStable('`* [ ] _ | ~`');
  });

  it('блок кода с символами разметки', () => {
    expectStable('```plaintext\n* [ ] _ | ~\n```');
  });
});
